"""Unit tests for FetchMissingData and CheckVASEligibility tools."""

from __future__ import annotations

from agent.tools.check_vas_eligibility import check_vas_eligibility
from agent.tools.fetch_missing_data import fetch_missing_data
from mock_backends.adapters import billing_profile, imei_registry


def test_fetch_missing_data_resolves_activation_code(dynamodb_tables):
    result = fetch_missing_data(
        order_id="ORD-1", subscription_id="SUB-1", field="activation_code",
        fetch_from="eSIM Provisioning DB", lookup_key="ICCID-123",
    )
    assert result.success is True
    assert result.value is not None
    assert result.source == "eSIM Provisioning DB"


def test_fetch_missing_data_unknown_adapter_fails_gracefully(dynamodb_tables):
    result = fetch_missing_data(
        order_id="ORD-1", subscription_id="SUB-1", field="mystery_field",
        fetch_from="Nonexistent Adapter", lookup_key="key",
    )
    assert result.success is False
    assert result.error_type == "UNKNOWN_ADAPTER"


def test_fetch_missing_data_resolves_netflix_vas_account_ref_on_retry(dynamodb_tables):
    """Real bug found during a live demo: fetch_from="Netflix Partner API"
    (generated by validate_order.py for any missing VAS field) had NO
    dispatch entry at all — every VAS fetch hit UNKNOWN_ADAPTER and
    escalated, even though FR test scenario 6 explicitly requires VAS
    entitlement failures to auto-resolve via partner API retry. Using
    retry_attempt=1 for a deterministic assertion, since Netflix's mock
    provision() has a 40% random first-attempt failure rate by design."""
    result = fetch_missing_data(
        order_id="ORD-1", subscription_id="SUB-1", field="vas_account_ref",
        fetch_from="Netflix Partner API", lookup_key="SUB-1", retry_attempt=1,
    )
    assert result.success is True
    assert result.error_type is None
    assert result.source == "Netflix Partner API"


def test_fetch_missing_data_resolves_billing_profile(dynamodb_tables):
    """Billing Profile DB was also missing from _ADAPTER_DISPATCH — a
    smaller, related gap found while fixing the VAS partner dispatch issue."""
    billing_profile.link_billing_profile("CUST-1", "BP-001")
    result = fetch_missing_data(
        order_id="ORD-1", subscription_id="SUB-1", field="billing_profile_id",
        fetch_from="Billing Profile DB", lookup_key="CUST-1",
    )
    assert result.success is True
    assert result.value == "BP-001"


def test_fetch_missing_data_records_backend_error_on_blacklisted_imei(dynamodb_tables):
    imei_registry.mark_blacklisted("IMEI-BLACKLISTED")
    result = fetch_missing_data(
        order_id="ORD-1", subscription_id="SUB-1", field="imei",
        fetch_from="IMEI Registry", lookup_key="IMEI-BLACKLISTED",
    )
    assert result.success is False
    assert result.error_type == "VALIDATION_FAILED"


